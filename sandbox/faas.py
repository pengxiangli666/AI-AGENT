"""FaaS-style deployment: run generated code as a locked-down container and publish it via Nginx.

Flow of ``deploy``:
  1. detect how to start the app (``detect_start_cmd``)
  2. write the files under ``apps_dir/<app_id>`` and start a container on the *internal*
     faas network (no internet egress) with the same hardening flags as the test sandbox
  3. wait until it answers HTTP on port 8000
  4. render an Nginx server block for ``<app_id>.<domain>``, validate (``nginx -t``), reload
  5. return the URL; on any failure everything created so far is rolled back
"""
from __future__ import annotations

import asyncio
import json
import os
import re
import shutil
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Awaitable, Callable

from .runner import SECCOMP_DEFAULT, UnsafePath, materialize_workspace

APP_PORT = 8000
LABEL = "agent.faas=1"

DockerFn = Callable[..., Awaitable[tuple[int, str, str]]]


@dataclass
class FaasConfig:
    image: str = "coding-agent-sandbox:latest"
    domain: str = "localhost"
    public_port: int = 8080              # port nginx is published on (omit from URL when 80)
    network: str = "agent-faas"          # internal docker network shared with nginx
    nginx_container: str = "coding-agent-nginx-1"
    nginx_conf_dir: str = "./deploy/nginx/conf.d"
    apps_dir: str = "./data/apps"
    seccomp_profile: str = SECCOMP_DEFAULT
    memory: str = "256m"
    cpus: str = "0.5"
    pids_limit: int = 128
    ready_timeout: int = 30

    @classmethod
    def from_env(cls) -> "FaasConfig":
        e = os.environ
        d = cls()
        return cls(
            image=e.get("SANDBOX_IMAGE", d.image),
            domain=e.get("FAAS_DOMAIN", d.domain),
            public_port=int(e.get("FAAS_PUBLIC_PORT", d.public_port)),
            network=e.get("FAAS_NETWORK", d.network),
            nginx_container=e.get("NGINX_CONTAINER", d.nginx_container),
            nginx_conf_dir=e.get("NGINX_CONF_DIR", d.nginx_conf_dir),
            apps_dir=e.get("FAAS_APPS_DIR", d.apps_dir),
            seccomp_profile=e.get("SANDBOX_SECCOMP", d.seccomp_profile),
        )


@dataclass
class Deployment:
    app_id: str
    url: str
    host_port: int | None = None


class DeployError(RuntimeError):
    pass


async def _docker(*args: str) -> tuple[int, str, str]:
    p = await asyncio.create_subprocess_exec(
        "docker", *args, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE, stdin=asyncio.subprocess.DEVNULL
    )
    out, err = await p.communicate()
    return p.returncode or 0, out.decode(), err.decode()


# ------------------------------------------------------------------ pure helpers (unit-tested)
def detect_start_cmd(files: dict[str, str], runtime: str) -> str:
    """Decide how to start the app. Convention first, then light heuristics."""
    proc = files.get("Procfile", "")
    m = re.search(r"^web:\s*(.+)$", proc, re.M)
    if m:
        return m.group(1).strip()
    if runtime == "python":
        main = files.get("main.py", "")
        app = files.get("app.py", "")
        if "FastAPI(" in main:
            return f"uvicorn main:app --host 0.0.0.0 --port {APP_PORT}"
        if "FastAPI(" in app:
            return f"uvicorn app:app --host 0.0.0.0 --port {APP_PORT}"
        if "Flask(" in app:
            return f"flask --app app run --host 0.0.0.0 --port {APP_PORT}"
        if "Flask(" in main:
            return f"flask --app main run --host 0.0.0.0 --port {APP_PORT}"
        for cand in ("main.py", "app.py", "server.py"):
            if cand in files:
                return f"python {cand}"
    if runtime == "node":
        pkg = files.get("package.json")
        if pkg:
            try:
                if "start" in json.loads(pkg).get("scripts", {}):
                    return "npm start"
            except json.JSONDecodeError:
                pass
        for cand in ("server.js", "index.js", "app.js"):
            if cand in files:
                return f"node {cand}"
    raise DeployError("could not determine how to start the app (add a Procfile with a 'web:' line)")


def render_nginx_conf(app_id: str, domain: str) -> str:
    host = f"{app_id}.{domain}"
    return f"""# generated by sandbox/faas.py - do not edit
server {{
    listen 80;
    server_name {host};

    # resolved per-request through Docker DNS (see resolver in nginx.conf)
    set $upstream http://{app_id}:{APP_PORT};

    location / {{
        proxy_pass $upstream;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_read_timeout 60s;
    }}
}}
"""


def build_run_args(app_id: str, app_dir: str | Path, cmd: str, cfg: FaasConfig) -> list[str]:
    return [
        "run", "-d", "--name", app_id,
        "--label", LABEL, "--label", f"agent.faas.id={app_id}",
        "--network", cfg.network,                  # internal network: no internet egress
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "--security-opt", f"seccomp={cfg.seccomp_profile}",
        "--read-only", "--tmpfs", "/tmp:rw,size=64m,mode=1777",
        "--pids-limit", str(cfg.pids_limit),
        "--memory", cfg.memory, "--memory-swap", cfg.memory, "--cpus", cfg.cpus,
        "--user", "10001:10001",
        "-e", f"PORT={APP_PORT}", "-e", "HOME=/tmp",
        "-v", f"{Path(app_dir).resolve()}:/app:ro", "-w", "/app",
        "--restart", "no",
        cfg.image, "sh", "-c", cmd,
    ]


def public_url(app_id: str, cfg: FaasConfig) -> str:
    port = "" if cfg.public_port == 80 else f":{cfg.public_port}"
    return f"http://{app_id}.{cfg.domain}{port}"


# ------------------------------------------------------------------ orchestration
async def _reload_nginx(cfg: FaasConfig, docker: DockerFn) -> None:
    code, _, err = await docker("exec", cfg.nginx_container, "nginx", "-t")
    if code != 0:
        raise DeployError(f"nginx config invalid: {err.strip()}")
    code, _, err = await docker("exec", cfg.nginx_container, "nginx", "-s", "reload")
    if code != 0:
        raise DeployError(f"nginx reload failed: {err.strip()}")


async def _wait_ready(app_id: str, cfg: FaasConfig, docker: DockerFn) -> None:
    """Probe from inside the nginx container (same network the proxy uses)."""
    loop = asyncio.get_running_loop()
    deadline = loop.time() + cfg.ready_timeout
    while loop.time() < deadline:
        code, out, _ = await docker("inspect", "-f", "{{.State.Running}}", app_id)
        if code != 0 or out.strip() != "true":
            _, logs, logs_err = await docker("logs", "--tail", "40", app_id)
            raise DeployError(f"app exited during startup:\n{(logs + logs_err)[-1500:]}")
        # busybox wget: exit 0 = 2xx, exit 8 = server answered with an HTTP error (still alive)
        code, _, _ = await docker("exec", cfg.nginx_container, "wget", "-q", "-O", "/dev/null", "-T", "2", f"http://{app_id}:{APP_PORT}/")
        if code in (0, 8):
            return
        await asyncio.sleep(0.5)
    raise DeployError(f"app did not become ready within {cfg.ready_timeout}s")


async def deploy(files: dict[str, str], runtime: str, cfg: FaasConfig | None = None, *, docker: DockerFn = _docker) -> Deployment:
    cfg = cfg or FaasConfig.from_env()
    cmd = detect_start_cmd(files, runtime)
    app_id = f"app-{uuid.uuid4().hex[:8]}"
    apps_root = Path(cfg.apps_dir)
    apps_root.mkdir(parents=True, exist_ok=True)
    conf_dir = Path(cfg.nginx_conf_dir)
    conf_dir.mkdir(parents=True, exist_ok=True)
    conf_path = conf_dir / f"{app_id}.conf"

    try:
        tmp = materialize_workspace(files, base=str(apps_root))   # validates paths, writes files
    except UnsafePath as e:
        raise DeployError(f"unsafe file path: {e}") from e
    app_dir = apps_root / app_id
    tmp.rename(app_dir)
    os.chmod(app_dir, 0o755)

    try:
        code, _, err = await docker(*build_run_args(app_id, app_dir, cmd, cfg))
        if code != 0:
            raise DeployError(f"docker run failed: {err.strip()}")
        await _wait_ready(app_id, cfg, docker)
        conf_path.write_text(render_nginx_conf(app_id, cfg.domain))
        await _reload_nginx(cfg, docker)
    except Exception:
        # roll back everything created so far
        conf_path.unlink(missing_ok=True)
        await docker("rm", "-f", app_id)
        shutil.rmtree(app_dir, ignore_errors=True)
        raise
    return Deployment(app_id=app_id, url=public_url(app_id, cfg))


async def teardown(app_id: str, cfg: FaasConfig | None = None, *, docker: DockerFn = _docker) -> bool:
    if not re.fullmatch(r"app-[0-9a-f]{8}", app_id):
        raise ValueError("invalid app_id")
    cfg = cfg or FaasConfig.from_env()
    existed = (Path(cfg.nginx_conf_dir) / f"{app_id}.conf").exists()
    (Path(cfg.nginx_conf_dir) / f"{app_id}.conf").unlink(missing_ok=True)
    await docker("rm", "-f", app_id)
    shutil.rmtree(Path(cfg.apps_dir) / app_id, ignore_errors=True)
    if existed:
        await _reload_nginx(cfg, docker)
    return existed


def list_deployments(cfg: FaasConfig | None = None) -> list[Deployment]:
    cfg = cfg or FaasConfig.from_env()
    conf_dir = Path(cfg.nginx_conf_dir)
    if not conf_dir.exists():
        return []
    return [Deployment(app_id=p.stem, url=public_url(p.stem, cfg)) for p in sorted(conf_dir.glob("app-*.conf"))]
